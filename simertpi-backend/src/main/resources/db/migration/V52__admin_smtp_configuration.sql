CREATE SCHEMA IF NOT EXISTS identity;

CREATE TABLE identity.admin_smtp_configuration (
    id UUID PRIMARY KEY,
    version BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    provider VARCHAR(16) NOT NULL CHECK (provider IN ('GMAIL', 'CUSTOM')),
    display_name VARCHAR(150) NOT NULL,
    from_address VARCHAR(255) NOT NULL,
    smtp_host VARCHAR(253) NOT NULL,
    smtp_port INTEGER NOT NULL CHECK (smtp_port BETWEEN 1 AND 65535),
    security_mode VARCHAR(16) NOT NULL CHECK (security_mode IN ('STARTTLS', 'SMTPS')),
    smtp_username VARCHAR(255) NOT NULL,
    credential_nonce BYTEA NOT NULL CHECK (octet_length(credential_nonce) = 12),
    credential_ciphertext BYTEA NOT NULL CHECK (octet_length(credential_ciphertext) >= 16),
    state VARCHAR(16) NOT NULL CHECK (state IN ('DRAFT', 'ACTIVE', 'SUPERSEDED', 'DISABLED')),
    reason VARCHAR(500),
    created_by VARCHAR(150) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by VARCHAR(150) NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    activated_at TIMESTAMPTZ,
    row_version BIGINT NOT NULL DEFAULT 0
);

CREATE UNIQUE INDEX uq_admin_smtp_single_draft
    ON identity.admin_smtp_configuration ((state)) WHERE state = 'DRAFT';
CREATE UNIQUE INDEX uq_admin_smtp_single_active
    ON identity.admin_smtp_configuration ((state)) WHERE state = 'ACTIVE';
CREATE INDEX ix_admin_smtp_history ON identity.admin_smtp_configuration (version DESC);

CREATE TABLE identity.admin_smtp_test_attempt (
    id UUID PRIMARY KEY,
    configuration_id UUID NOT NULL REFERENCES identity.admin_smtp_configuration(id),
    test_kind VARCHAR(24) NOT NULL CHECK (test_kind IN ('CONNECTION', 'EMAIL')),
    result VARCHAR(16) NOT NULL CHECK (result IN ('STARTED', 'SUCCESS', 'FAILURE', 'RATE_LIMITED')),
    actor VARCHAR(150) NOT NULL,
    recipient_fingerprint VARCHAR(64),
    failure_code VARCHAR(64),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX ix_admin_smtp_test_attempt_recent
    ON identity.admin_smtp_test_attempt (created_at DESC, actor, test_kind);

COMMENT ON TABLE identity.admin_smtp_configuration IS 'Versioned SMTP settings; credentials use authenticated encryption and are never returned by API.';
COMMENT ON TABLE identity.admin_smtp_test_attempt IS 'Rate-limit and audit metadata for SMTP probes; no credentials or message content.';
